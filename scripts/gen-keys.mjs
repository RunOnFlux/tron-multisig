#!/usr/bin/env node
// Create TEST keys for a deployment to a test network (Nile):
//
//   node scripts/gen-keys.mjs --network nile [--force]
//
// Writes deploy/keys/<network>.json (gitignored, mode 600) with a deployer, S (energy account), the
// sponsor owner, one relayer and a fee collector, and prints the ADDRESSES only. scripts/deploy.mjs
// reads the file through DEPLOY_KEYS_FILE. Mainnet keys are never generated here: they belong to
// whoever holds them (see DEPLOYING.md).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { keyFromPriv } from '../test/helpers/keys.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { values: opts } = parseArgs({
  options: {
    network: { type: 'string' },
    force: { type: 'boolean', default: false },
  },
});

if (opts.network !== 'nile') {
  console.error(
    'gen-keys: only --network nile is supported (mainnet keys are not generated by a script)',
  );
  process.exit(2);
}

const dir = path.join(ROOT, 'deploy', 'keys');
const file = path.join(dir, `${opts.network}.json`);
if (fs.existsSync(file) && !opts.force) {
  console.error(
    `gen-keys: ${path.relative(ROOT, file)} already exists (it may hold funded keys); pass --force to replace it`,
  );
  process.exit(1);
}

/** A uniformly random valid secp256k1 private key. */
function newKey(name) {
  for (;;) {
    try {
      return keyFromPriv(crypto.randomBytes(32).toString('hex'), name);
    } catch {
      // out-of-range scalar (probability ≈ 2^-128): draw again
    }
  }
}

const entry = (k) => ({ address: k.base58, privateKey: k.priv });
const keys = {
  network: opts.network,
  createdAt: new Date().toISOString(),
  note: 'TEST keys for a test network only. Never fund them with mainnet TRX.',
  deployer: entry(newKey('deployer')),
  s: entry(newKey('s')),
  owner: entry(newKey('owner')),
  relayers: [entry(newKey('relayer'))],
  feeCollector: entry(newKey('feeCollector')),
};

fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
fs.writeFileSync(file, JSON.stringify(keys, null, 2) + '\n', { mode: 0o600 });
fs.chmodSync(file, 0o600);

console.log(`wrote ${path.relative(ROOT, file)} (mode 600). Addresses:`);
console.log(`  deployer      ${keys.deployer.address}`);
console.log(`  s             ${keys.s.address}`);
console.log(`  owner         ${keys.owner.address}`);
console.log(`  relayer       ${keys.relayers[0].address}`);
console.log(`  feeCollector  ${keys.feeCollector.address}`);
